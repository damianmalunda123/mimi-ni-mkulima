-- ----------------------------------------------------------------------------
-- 3. Public Content Feed (Chronological with Cursor Pagination)
-- Optimized by idx_posts_created_at_desc
-- ----------------------------------------------------------------------------
SELECT 
    p.id,
    p.title,
    p.content,
    p.media_url,
    p.created_at,
    u.username,
    u.id AS author_id
FROM posts p
JOIN users u ON u.id = p.user_id
ORDER BY p.created_at DESC
LIMIT 20;

-- ----------------------------------------------------------------------------
-- 4. Lightning-Fast Full-Text Search (Uses GIN Index)
-- Matches query keywords, handles variations, and ranks by relevance
-- ----------------------------------------------------------------------------
SELECT 
    p.id,
    p.title,
    p.content,
    p.media_url,
    p.created_at,
    u.username,
    ts_rank(p.search_vector, websearch_to_tsquery('english', 'mahindi mbegu')) AS rank
FROM posts p
JOIN users u ON u.id = p.user_id
WHERE p.search_vector @@ websearch_to_tsquery('english', 'mahindi mbegu')
ORDER BY rank DESC, p.created_at DESC
LIMIT 20;

-- ----------------------------------------------------------------------------
-- 5. AI Semantic Search via Vector Cosine Distance (Uses HNSW Index)
-- Finds conceptually similar posts even if keywords do not match exactly
-- ----------------------------------------------------------------------------
SELECT 
    p.id,
    p.title,
    p.content,
    p.media_url,
    1 - (pe.embedding <=> '[0.012, -0.039, /* ... 384 query vector ... */]'::vector(384)) AS similarity_score
FROM post_embeddings pe
JOIN posts p ON p.id = pe.post_id
ORDER BY pe.embedding <=> '[0.012, -0.039, /* ... 384 query vector ... */]'::vector(384) ASC
LIMIT 10;

-- ----------------------------------------------------------------------------
-- 6. Hybrid Search (Combining Full-Text Search + AI Vector Search)
-- Reciprocal Rank Fusion (RRF) for production-grade retrieval
-- ----------------------------------------------------------------------------
WITH fts_results AS (
    SELECT 
        id, 
        ROW_NUMBER() OVER (ORDER BY ts_rank(search_vector, websearch_to_tsquery('english', 'mahindi')) DESC) AS fts_rank
    FROM posts
    WHERE search_vector @@ websearch_to_tsquery('english', 'mahindi')
    LIMIT 30
),
vector_results AS (
    SELECT 
        p.id, 
        ROW_NUMBER() OVER (ORDER BY pe.embedding <=> '[/* ... 384 query vector ... */]'::vector(384) ASC) AS vec_rank
    FROM post_embeddings pe
    JOIN posts p ON p.id = pe.post_id
    LIMIT 30
)
SELECT 
    p.id,
    p.title,
    p.content,
    p.media_url,
    COALESCE(1.0 / (60 + fts.fts_rank), 0.0) + COALESCE(1.0 / (60 + vec.vec_rank), 0.0) AS hybrid_score
FROM posts p
LEFT JOIN fts_results fts ON p.id = fts.id
LEFT JOIN vector_results vec ON p.id = vec.id
WHERE fts.id IS NOT NULL OR vec.id IS NOT NULL
ORDER BY hybrid_score DESC
LIMIT 20;

